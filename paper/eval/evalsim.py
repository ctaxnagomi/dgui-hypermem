def make_corpus(n, rng):
    """Build the memory store. Returns (memories, contradictions)."""
    mems = []
    contradictions = []          # (new_id, old_id)
    seen = set()

    def add(session, mtype, text, tags, salience, **kw):
        mid = "m%05d" % len(mems)
        m = dict(id=mid, session=session, type=mtype, text=text,
                 tags=tags, salience=salience, status="active",
                 superseded_by=None, sal_seq=salience)
        m.update(kw)
        mems.append(m)
        return m

    # --- evolving configuration: the backbone of the temporal class ---------
    # Each subject is superseded more than once, so answering "what does X use
    # now" requires the *whole* supersede chain to have been maintained, not
    # merely one stale row to have been filtered.
    evolving = []
    pairs, seen_pair = [], set()
    while len(pairs) < 20:                       # distinct (subject, purpose)
        c, p = rng.choice(COMPS), rng.choice(PURPOSES)
        if (c, p) in seen_pair:
            continue
        seen_pair.add((c, p))
        pairs.append((c, p))
    for comp, purpose in pairs:
        chain_len = rng.choice([2, 2, 3, 3, 4])
        techs = rng.sample(TECHS, chain_len)
        sessions = sorted(rng.sample(range(1, 96), chain_len))
        prev = None
        for gen, (tech, sess) in enumerate(zip(techs, sessions)):
            cur = add(sess, "fact",
                      "%s uses %s for %s." % (comp, tech, purpose),
                      [comp, purpose.split()[0]], 3.0 + 0.4 * gen + rng.random() * 0.5)
            if prev is not None:
                prev["status"] = "superseded"
                prev["superseded_by"] = cur["id"]
                cur["supersedes"] = prev["id"]
                contradictions.append((cur["id"], prev["id"]))
            prev = cur
        evolving.append(dict(comp=comp, purpose=purpose, cur=prev,
                             stale=[m["id"] for m in mems
                                    if m.get("superseded_by") == prev["id"]],
                             chain=[m for m in mems if m["text"].startswith(comp)
                                    and purpose in m["text"]]))

    # --- filler that gives the corpus realistic distractors -----------------
    for i in range(n - len(mems)):
        k = rng.random()
        comp = rng.choice(COMPS)
        session = rng.randint(1, 95)
        if k < 0.20:
            t, p = rng.choice(TECHS), rng.choice(PURPOSES)
            add(session, "decision",
                "We chose %s over %s for %s in %s because %s."
                % (t, rng.choice(ALTS), p, comp, rng.choice(RATIONALES)),
                [comp, "decision"], 4.0 + rng.random(), tech=t, purpose=p, comp=comp)
        elif k < 0.40:
            add(session, "solution",
                "%s in %s was caused by %s; fixed by %s."
                % (rng.choice(SYMPTOMS), comp, rng.choice(CAUSES), rng.choice(FIXES)),
                [comp, "solution"], 4.0 + rng.random(), comp=comp)
        elif k < 0.56:
            add(session, "project",
                "%s lives in %s. %s." % (comp, rng.choice(FILES),
                                         rng.choice(["Update it before schema changes",
                                                     "No direct imports allowed",
                                                     "Tests are colocated",
                                                     "Regenerate with make codegen",
                                                     "Do not edit by hand",
                                                     "Exported from the core package"])),
                [comp, "project"], 3.0 + rng.random(), comp=comp)
        elif k < 0.68:
            add(session, "architecture",
                "%s talks to %s over %s to coordinate %s."
                % (comp, rng.choice(COMPS), rng.choice(["gRPC", "Kafka", "HTTPS",
                                                         "NATS", "the outbox table"]),
                   rng.choice(PURPOSES)),
                [comp, "architecture"], 3.5 + rng.random(), comp=comp)
        elif k < 0.76:
            add(session, "preference",
                "The team prefers %s rather than %s for %s."
                % (rng.choice(CHOSEN), rng.choice(["long-lived branches",
                                                   "hand-written migrations",
                                                   "npm", "yaml config",
                                                   "a bespoke logger",
                                                   "code generation at build time"]),
                   rng.choice(PURPOSES)),
                [comp, "preference"], 3.0 + rng.random())
        elif k < 0.83:
            add(session, "fact",
                "Reproducing the %s issue needs %s." % (rng.choice(SYMS), rng.choice(FILES)),
                [comp, "repro"], 3.0 + rng.random(), comp=comp)
        elif k < 0.90:
            # near-duplicate restatement: the dedup path should collapse these
            base = rng.choice(mems)
            if base["type"] in ("decision", "architecture"):
                add(session, base["type"], base["text"],
                    base["tags"], base["salience"], dup_of=base["id"])
        else:
            add(session, "conversation",
                "Session %d: briefly weighed %s for %s and moved on."
                % (session, rng.choice(TECHS), rng.choice(PURPOSES)),
                [comp, "chatter"], 1.0 + rng.random())

    return mems, contradictions, evolving


def make_queries(mems, evolving, nq, rng):
    """Plant each query beside the exact memory that answers it."""
    by_id = {m["id"]: m for m in mems}
    decisions = [m for m in mems if m["type"] == "decision"]
    solutions = [m for m in mems if m["type"] == "solution"]
    projects = [m for m in mems if m["type"] == "project"]
    archs = [m for m in mems if m["type"] == "architecture"]
    facts = [m for m in mems if m["type"] == "fact" and m["status"] == "active"]

    qs = []

    def q(text, cls, gold, stale=()):
        qs.append(dict(qid="q%04d" % len(qs), text=text, cls=cls,
                       gold=list(gold), stale=list(stale)))

    # 1. lexical -- must be found by exact rare tokens (paths, tech names)
    for m in rng.sample(projects, min(len(projects), nq // 4)):
        f = re.search(r"([\w./-]+\.(?:ts|sql|py|go|yml|yaml|json|tf)|Makefile|[\w./-]+)",
                      m["text"])
        if f:
            q("what is in %s" % f.group(1), "lexical", [m["id"]])

    # 2. semantic -- same meaning, disjoint content words. Two phrasings per
    #    subject so the class is not the smallest pool in the mix.
    for e in evolving:
        syn = SYN.get(e["purpose"])
        if syn:
            q("how does %s handle %s?" % (e["comp"], syn), "semantic", [e["cur"]["id"]])
            q("in %s, how is %s handled?" % (e["comp"], syn), "semantic", [e["cur"]["id"]])

    # 3. temporal -- current value wins; every earlier generation is a distractor
    for e in evolving:
        q("which technology does %s rely on for %s these days?"
          % (e["comp"], e["purpose"]), "temporal", [e["cur"]["id"]], e["stale"])

    # 3b. mid-chain: name an intermediate generation, so the answer is a
    # superseded row and the system must be able to recall history at all
    for e in evolving:
        hist = [m for m in e["chain"] if m["id"] != e["cur"]["id"]]
        if hist:
            h = hist[len(hist) // 2]
            if "uses" in h["text"]:
                tech = h["text"].split(" uses ")[1].split(" for ")[0]
                q("back when %s depended on %s, what was that for?"
                  % (e["comp"], tech), "temporal", [h["id"]], [e["cur"]["id"]])

    # 4. pinpoint -- rationale / diagnosis, phrased as a question
    for m in rng.sample(decisions, min(len(decisions), nq // 5)):
        t = m.get("tech")
        if t:
            q("what was the argument for picking %s?" % t, "pinpoint", [m["id"]])
    for m in rng.sample(solutions, min(len(solutions), nq // 5)):
        head = m["text"].split(" in ")[0]
        q("what fixed the problem where %s?" % head, "pinpoint", [m["id"]])
    for m in rng.sample(archs, min(len(archs), nq // 8)):
        c = m.get("comp")
        if c:
            q("how is %s wired into the rest of the platform?" % c, "pinpoint", [m["id"]])
    for m in rng.sample(facts, min(len(facts), nq // 6)):
        if "Reproducing" in m["text"]:
            f = m["text"].split("needs ")[-1].rstrip(".")
            q("what do I need in order to reproduce the bug again?", "lexical", [m["id"]])

    # Quota per class first, so truncating to --n-q keeps the mix even instead of
    # leaving whatever happened to be generated last.
    by_cls = defaultdict(list)
    for x in qs:
        by_cls[x["cls"]].append(x)
    for c in by_cls:
        rng.shuffle(by_cls[c])
    order = sorted(by_cls)
    quota = max(1, nq // len(order))
    sel = []
    for c in order:
        sel.extend(by_cls[c][:quota])
    # spill any shortfall into the classes that still have depth
    short = nq - len(sel)
    for c in sorted(order, key=lambda c: -len(by_cls[c])):
        if short <= 0:
            break
        take = by_cls[c][quota:][:short]
        sel.extend(take)
        short -= len(take)
    rng.shuffle(sel)
    return sel[:nq]