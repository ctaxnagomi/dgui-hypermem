"""Simulated long-horizon memory benchmark for DGUI-HyperMem.

WHAT THIS IS
------------
A *simulation*, not DeepSWE. DeepSWE is a real 113-task software-engineering
agent benchmark whose harness needs paid proprietary endpoints and an air-gapped
runner; none of that is available offline. What follows reproduces the memory
*behaviour* such a benchmark exercises -- persistent facts, stated rationales,
symptom/fix records, evolving configuration, and contradictions across many
sessions -- and measures retrieval quality over it.

Every label is exact by construction: each query is planted alongside the memory
that answers it, so relevance is never judged by a model.

WHAT IS FAITHFUL TO PRODUCTION
------------------------------
* dense channel  : BAAI/bge-base-en-v1.5, 768d, L2-normalised -- byte-identical
                   to the embedding model the deployed index uses
* lexical channel: Okapi BM25 over Porter-stemmed tokens, matching SQLite
                   FTS5 `tokenize='porter unicode61'`
* fusion         : reciprocal rank fusion with RRF_K = 60, the deployed constant
* final scoring  : the deployed linear blend, character for character
                   JEV off : 0.85*fused + 0.15*salience
                   JEV on  : 0.50*fused + 0.40*jev   + 0.10*salience
* supersede gate : p >= 0.80, the deployed threshold

WHAT IS SIMULATED
-----------------
* the JEV reasoning call. A reranking stage is real and load-bearing, but JEV
  itself is a hosted reasoning backend, so the fourth system substitutes a local
  cross-encoder. Its column is labelled CE and is NOT JEV performance; it
  measures the value of *adding a relevance-judging stage over the fused
  shortlist*, which is the architectural claim under test.
* salience and memory-type assignment on the write side, which are JEV outputs
  in production, are generated by deterministic keyword rules.
* recency ordering, which stands in for a filesystem crawl order.

Run:  python evalsim.py --out <dir> [--n-mem 900] [--n-q 150] [--seed 11]
"""
