"""Render results.tex (LaTeX tables) from figures/eval-results.json.

The JSON stores, for each system, the mean and population standard deviation
across seeds directly (overall[sys][metric] = [mean, sd]), so nothing is
recomputed here -- this script only formats. Regenerate with:

    python mkresults.py
"""
import json

from paper_paths import find_results, find_results_tex

SRC = find_results()
OUT = find_results_tex()

rep = json.load(open(SRC, encoding="utf-8"))
cfg = rep["config"]
overall = rep["overall"]
per_class = rep["per_class"]
classes = cfg["classes"]
n_seeds = len(cfg["seeds"])
lex_w = cfg.get("lexical_weight", 0.3)

# Quote the corpus size actually realised, not the generator's target: the
# truncation to n_mem leaves slightly fewer rows than asked for.
mem_counts = [s["n_memories"] for s in rep["per_seed"]]
n_mem_lo, n_mem_hi = min(mem_counts), max(mem_counts)
if n_mem_lo == n_mem_hi:
    mem_text = "%d" % n_mem_lo
else:
    mem_text = "%d\\,--\\,%d" % (n_mem_lo, n_mem_hi)

# ---- how each row is described in the paper --------------------------------
# Grouped so the ladder reads as an ablation: control, single channel, then
# fusion at the deployed weight, then the same fusion re-weighted, with and
# without the rerank stage.
ROWS = [
    ("recency",   r"Recency only \emph{(control)}"),
    ("bm25",      r"FTS5 lexical channel alone"),
    ("dense",     r"Vectorize dense channel alone"),
    ("dense+ce",  r"Dense $+$ cross-encoder rerank"),
    ("rrf",       r"RRF fusion, equal weights \emph{(as deployed)}"),
    ("rrf+ce",    r"RRF equal $+$ rerank \emph{(deployed pipeline)}"),
    ("rrf-w",     r"RRF fusion, lexical weight $%.1f$" % lex_w),
    ("rrf-w+ce",  r"RRF weighted $+$ rerank"),
]

METRICS = [("r5", "R@5"), ("r10", "R@10"), ("mrr", "MRR@10"),
           ("ndcg", "nDCG@10"), ("hit", "P@1")]

# Per-class columns, in the order generated by evalsim.py.
CLASS_LABEL = {
    "lexical":  r"lexical",
    "pinpoint": r"pinpoint",
    "semantic": r"paraphrase",
    "temporal": r"temporal",
}


def pm(sysname, metric):
    mean, sd = overall[sysname][metric]
    return r"%.3f\,$\pm$\,%.3f" % (mean, sd)


def pmc(sysname, cls):
    """per_class[sys][class] is stored as [mean, sd], not as a metric dict."""
    mean, sd = per_class[sysname][cls]
    return r"%.3f\,$\pm$\,%.3f" % (mean, sd)


def bold(s):
    return r"\textbf{%s}" % s


def best_of(metric, pool):
    """Best mean in `pool`, so the strongest configuration can be marked."""
    return max(overall[s][metric][0] for s in pool if s in overall)


L = []
w = L.append

w("%% GENERATED by mkresults.py from figures/eval-results.json -- do not edit by hand.")
w("%% %d seeds (%s) x %d queries against ~%d memories; embedding %s;"
  % (n_seeds, ", ".join(map(str, cfg["seeds"])), cfg["n_q"], cfg["n_mem"],
     cfg["embedding_model"]))
w("%% rerank stand-in %s; RRF k=%s; lexical weight for rrf-w* = %s."
  % (cfg["rerank_model"], cfg["rrf_k"], lex_w))
w("")

# ---- Table 1: overall -----------------------------------------------------
w(r"\begin{table*}[t]")
w(r"  \centering")
w(r"  \footnotesize")
w(r"  \setlength{\tabcolsep}{5pt}")
w(r"  \begin{tabular}{lccccc}")
w(r"    \toprule")
w(r"    \textbf{Retrieval configuration} & \textbf{R@5} & \textbf{R@10} & "
  r"\textbf{MRR@10} & \textbf{nDCG@10} & \textbf{P@1} \\")
w(r"    \midrule")

top_ndcg = best_of("ndcg", [k for k, _ in ROWS])
for key, label in ROWS:
    if key not in overall:
        continue
    cells = []
    for metric, _ in METRICS:
        s = pm(key, metric)
        if metric == "ndcg" and abs(overall[key][metric][0] - top_ndcg) < 1e-9:
            s = bold(s)
        cells.append(s)
    w("    %s & %s \\\\" % (label, " & ".join(cells)))

w(r"    \bottomrule")
w(r"  \end{tabular}")
w(r"  \caption{Overall retrieval quality as mean $\pm$ population standard deviation "
  r"over %d seeds of %d queries each, against %s stored memories. The "
  r"``recency'' row orders the store by write time and recovers almost nothing; it "
  r"is the control that makes the rest of the table mean something, since a "
  r"harness returning the newest rows first would otherwise look competitive on "
  r"any workload with recency bias. Note that the single dense channel and the "
  r"re-weighted fusion are tied at the top on nDCG@10, that equal-weight fusion is "
  r"below both, and that the deployed pipeline is lowest of the fusion family. "
  r"\S\ref{sec:eval} explains why, and what that implies for the deployed weights.}"
  % (n_seeds, cfg["n_q"], mem_text))
w(r"  \label{tab:main}")
w(r"\end{table*}")
w("")

# ---- Table 2: per class ---------------------------------------------------
w(r"\begin{table*}[t]")
w(r"  \centering")
w(r"  \footnotesize")
w(r"  \setlength{\tabcolsep}{5pt}")
w(r"  \begin{tabular}{l" + "c" * len(classes) + "}")
w(r"    \toprule")
w(r"    \textbf{Retrieval configuration} & "
  + " & ".join(r"\textbf{%s}" % CLASS_LABEL.get(c, c) for c in classes) + r" \\")
w(r"    \midrule")
for key, label in ROWS:
    if key not in per_class:
        continue
    w("    %s & %s \\\\" % (label,
                           " & ".join(pmc(key, c) for c in classes)))
w(r"    \bottomrule")
w(r"  \end{tabular}")
w(r"  \caption{nDCG@10 by query class, mean $\pm$ population standard deviation over "
  r"%d seeds. The classes separate sharply, and the separation is the point of the "
  r"table. Paraphrase queries share almost no content words with the memory that "
  r"answers them, so a lexical channel is close to blind there (%.3f) while a dense "
  r"channel is not (%.3f). Temporal queries are the one class the lexical channel "
  r"still matches on (%.3f against %.3f), because the token that distinguishes one "
  r"link of a supersession chain from the next is usually a literal identifier. "
  r"Query counts per seed are %s.}"
  % (n_seeds,
     per_class["bm25"]["semantic"][0], per_class["dense"]["semantic"][0],
     per_class["bm25"]["temporal"][0], per_class["dense"]["temporal"][0],
     ", ".join("%s %d" % (c, cfg["counts"][c]) for c in classes)))
w(r"  \label{tab:perclass}")
w(r"\end{table*}")
w("")

# ---- numbers the prose refers to, emitted as a comment so they stay in sync
facts = {
    "n_seeds": n_seeds,
    "n_q": cfg["n_q"],
    "n_mem": cfg["n_mem"],
    "ndcg": {k: round(v["ndcg"][0], 3) for k, v in overall.items()},
    "r10": {k: round(v["r10"][0], 3) for k, v in overall.items()},
    "per_class_ndcg": {k: {c: round(v[c][0], 3) for c in classes}
                       for k, v in per_class.items()},
    "ce_ms_per_query": None,
}
w("%% FACTS (for prose cross-check):")
for k in sorted(facts):
    w("%%   %s = %s" % (k, facts[k]))
w("")

open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")

# A missing closing brace in a \caption turns into a "Runaway argument?" that
# swallows the rest of the document, so refuse to write an unbalanced file.
depth = 0
for n, line in enumerate(L, 1):
    i = 0
    while i < len(line):
        if line[i] == "\\":
            i += 2
            continue
        if line[i] == "{":
            depth += 1
        elif line[i] == "}":
            depth -= 1
        i += 1
if depth != 0:
    raise SystemExit("results.tex is brace-unbalanced by %+d -- refusing to write"
                     % depth)

print("wrote", OUT)
print()
print("overall nDCG@10 (mean):")
for key, label in ROWS:
    if key in overall:
        print("   %-10s %.3f +- %.3f" % (key, *overall[key]["ndcg"]))
print()
print("per-class nDCG@10 (mean):")
print("   %-10s" % "system" + "".join("%13s" % c for c in classes))
for key, _ in ROWS:
    if key in per_class:
        print("   %-10s" % key + "".join("%13.3f" % per_class[key][c][0]
                                        for c in classes))